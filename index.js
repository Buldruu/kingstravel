function toggleProv(uid) {
  const detail = document.getElementById(uid + "-detail");
  const icon = document.getElementById(uid + "-icon");
  const btn = detail.previousElementSibling;
  const isOpen =
    detail.style.maxHeight !== "0px" && detail.style.maxHeight !== "";

  $$(".prov-detail").forEach((d) => {
    d.style.maxHeight = "0px";
  });
  $$(".prov-toggle").forEach((b) => b.setAttribute("aria-expanded", "false"));
  $$("[id$='-icon']").forEach((ic) => {
    if (ic.id.startsWith("prov-")) ic.textContent = "+";
  });

  if (!isOpen) {
    detail.style.maxHeight = detail.scrollHeight + "px";
    btn.setAttribute("aria-expanded", "true");
    icon.textContent = "−";
  }
}

