// ========== Hero Slider ==========
const HERO_SLIDES = [
  "img/nuur.jpg",
  "img/slide2.jpg",
  "img/slide3.jpg",
  "img/slide4.jpg",
];
let heroIndex = 0;

function setHeroSlide(i) {
  heroIndex = (i + HERO_SLIDES.length) % HERO_SLIDES.length;
  document.documentElement.style.setProperty(
    "--hero-img",
    `url("${HERO_SLIDES[heroIndex]}")`,
  );
  $$(".hs-dot").forEach((d, idx) =>
    d.classList.toggle("is-active", idx === heroIndex),
  );
}

function setupHeroSlider() {
  const dotsWrap = $("#hsDots");
  dotsWrap.innerHTML = HERO_SLIDES.map(
    (_, idx) =>
      `<button class="hs-dot ${idx === 0 ? "is-active" : ""}" data-idx="${idx}" aria-label="Slide ${idx + 1}" type="button"></button>`,
  ).join("");

  dotsWrap.addEventListener("click", (e) => {
    const btn = e.target.closest(".hs-dot");
    if (btn) setHeroSlide(Number(btn.dataset.idx));
  });
  $("#hsPrev").addEventListener("click", () => setHeroSlide(heroIndex - 1));
  $("#hsNext").addEventListener("click", () => setHeroSlide(heroIndex + 1));
  window.addEventListener("keydown", (e) => {
    if (e.key === "ArrowLeft") setHeroSlide(heroIndex - 1);
    if (e.key === "ArrowRight") setHeroSlide(heroIndex + 1);
  });

  // Auto-advance every 6s
  setInterval(() => setHeroSlide(heroIndex + 1), 6000);
  setHeroSlide(0);
}

// ========== Section Progress Dots ==========
const SECTION_IDS = [
  "hero",
  "destinations",
  "provinces",
  "packages",
  "services",
  "reviews",
  "faq",
  "contact",
];

function setupSectionProgress() {
  const prog = $("#sectionProgress");
  const dots = $$(".sp-dot");

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          const id = entry.target.id;
          const idx = SECTION_IDS.indexOf(id);
          dots.forEach((d, i) => d.classList.toggle("active", i === idx));
        }
      });
    },
    { threshold: 0.35 },
  );

  SECTION_IDS.forEach((id) => {
    const el = document.getElementById(id);
    if (el) observer.observe(el);
  });

  // Show after scroll
  window.addEventListener("scroll", () => {
    prog.classList.toggle("is-visible", window.scrollY > 300);
  });
}

// ========== Scroll Reveal ==========
function setupReveal() {
  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("is-visible");
          observer.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.12 },
  );

  $$(".reveal").forEach((el) => observer.observe(el));
}

